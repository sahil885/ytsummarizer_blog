export default function sitemap(): MetadataRoute.Sitemap {
  const baseUrl = 'https://ytsummarizer-blog.vercel.app'

  const posts = Object.keys(postDates).filter((slug) => !NOINDEX_SLUGS.has(slug))

  const blogPosts = posts.map((slug) => ({
    url: `${baseUrl}/blog/${slug}`,
    lastModified: new Date(postDates[slug]),
    changeFrequency: 'monthly' as const,
    priority: 0.8,
  }))

  const archivePages = Array.from({ length: totalPages - 1 }, (_, i) => ({
    url: `${baseUrl}/page/${i + 2}`,
    lastModified: new Date(),
    changeFrequency: 'weekly' as const,
    priority: 0.5,
  }))

  return [
    {
      url: baseUrl,
      lastModified: new Date(),
      changeFrequency: 'weekly',
      priority: 1,
    },
    ...archivePages,
    ...blogPosts,
  ]
}
